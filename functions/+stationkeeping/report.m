function report(result,output_directory)
%REPORT Export the setup/results tables using the saved campaign settings.
%
% PROTOTYPE:
%   stationkeeping.report(result, output_directory)
%
% DESCRIPTION:
%   Read settings and branch statistics from the supplied result,
%   preserving the replayed experiment. Save full-precision setup and
%   left/right summary CSV files; round only the terminal display.
%   Stability labels and annual-cost headings follow the frozen study.
%
% INPUT:
%   result            stationkeeping.compute result or saved replay,
%                       containing settings, references.left/right,
%                       branches.left/right and origin. Statistics
%                       follow stationkeeping.statistics; phases are
%                       rad, and annual costs are m/s per 365-day trial.
%   output_directory  Destination folder, created if absent.
%
% OUTPUT:
%   None. Writes stationkeeping_setup.csv (Quantity/Value/Unit) and
%   stationkeeping_results.csv (branch, stability, phase, completion
%   counts, mean and P99), replacing existing CSVs; prints both summaries.

% Build setup rows from the loaded result, retaining their actual physical units.
cfg = result.settings;
number = @(x) string(sprintf('%.17g',x));
quantity = ["Dynamical model";"Reference trajectories";"Left initial Sun phase"; ...
    "Right initial Sun phase";"Nominal correction interval";"Targeted state components"; ...
    "Position targeting tolerance";"vy targeting tolerance";"Newton damping"; ...
    "Maximum Newton iterations";"Requested-coast bounds";"Simulated duration"; ...
    "Trials per solution";"Random generator / seed (reset for each branch)"; ...
    "Orbit-determination delay";"Insertion/navigation position sigma per component"; ...
    "Insertion/navigation velocity sigma per component";"Execution sigma per commanded component"; ...
    "Propagation absolute tolerance";"Propagation relative tolerance"; ...
    "Distance unit";"Time unit";"Velocity unit"];
value = ["Spatial BCR4BP";"Left and right periodic solutions"; ...
    number(result.references.left.sun_phase_rad);number(result.references.right.sun_phase_rad); ...
    number(cfg.rpo_period_tu*cfg.units.days_per_tu);"x, y, z, vy"; ...
    number(cfg.targeting.position_tolerance_km);number(cfg.targeting.vy_tolerance_cm_s); ...
    number(cfg.targeting.damping);number(cfg.targeting.maximum_iterations); ...
    strjoin(compose('%.17g',cfg.targeting.coast_bounds_factor),'--');number(cfg.horizon_days); ...
    number(cfg.trials_per_branch);string(cfg.random_generator)+" / "+number(cfg.random_seed); ...
    number(cfg.navigation_delay_days);number(cfg.errors.position_sigma_km); ...
    number(cfg.errors.velocity_sigma_cm_s);number(100*cfg.errors.execution_sigma_fraction); ...
    number(cfg.propagation.absolute_tolerance);number(cfg.propagation.relative_tolerance); ...
    number(cfg.units.DU_km);number(cfg.units.TU_s);number(cfg.units.VU_km_s)];
unit = ["";"";"rad";"rad";"days";"";"km";"cm/s";"";""; ...
    "times requested interval";"days";"";"";"days";"km";"cm/s";"percent"; ...
    "normalized units";"normalized units";"km";"s";"km/s"];
setup = table(quantity,value,unit,'VariableNames',{'Quantity','Value','Unit'});

% Report completion counts alongside finite completed-trial cost statistics.
left = result.branches.left; right = result.branches.right;
comparison = table(["Left";"Right"],["Unstable";"Stable"], ...
    [result.references.left.sun_phase_rad;result.references.right.sun_phase_rad], ...
    [left.statistics.valid_trials;right.statistics.valid_trials], ...
    [numel(left.completed);numel(right.completed)], ...
    [left.statistics.mean_m_s;right.statistics.mean_m_s], ...
    [left.statistics.p99_m_s;right.statistics.p99_m_s], ...
    'VariableNames',{'Solution','InPlaneStability','SunPhase_rad','ValidTrials', ...
    'TotalTrials','Mean_m_s_per_year','P99_m_s_per_year'});

% Write the two tables at full precision before formatting terminal output.
if ~isfolder(output_directory), mkdir(output_directory); end
writetable(setup,fullfile(output_directory,'stationkeeping_setup.csv'));
writetable(comparison,fullfile(output_directory,'stationkeeping_results.csv'));
fprintf('\nStationkeeping setup (%s)\n',result.origin);
% Keep full precision in CSV; avoid binary-rounding clutter in the terminal.
terminal_setup = setup;
numeric_rows = ~isnan(str2double(setup.Value));
terminal_setup.Value(numeric_rows) = compose('%.10g',str2double(setup.Value(numeric_rows)));
disp(terminal_setup);
fprintf('One-year results [m/s/year]:\n');
for k = 1:height(comparison)
    fprintf('  %s (%s): %d/%d valid; mean %.2f; P99 %.2f\n', ...
        comparison.Solution(k),comparison.InPlaneStability(k),comparison.ValidTrials(k), ...
        comparison.TotalTrials(k),comparison.Mean_m_s_per_year(k),comparison.P99_m_s_per_year(k));
end
fprintf('Tables saved under %s\n',output_directory);
end
