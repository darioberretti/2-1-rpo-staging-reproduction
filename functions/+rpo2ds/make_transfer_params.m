function params = make_transfer_params(settings, target, target_frame, theta_sun0_value)
%MAKE_TRANSFER_PARAMS Map frozen Run 02 settings onto RPO2DS_transfer inputs.
%
% PROTOTYPE:
%   params = rpo2ds.make_transfer_params(settings, target, target_frame, theta_sun0_value)
%
% DESCRIPTION:
%   Translate study settings into the transfer solver's explicit parameter
%   fields, retaining its current defaults for omitted settings. The Run 02
%   calls use free geometry, standard operation, and no prescribed RPO phase.
%
% INPUT:
%   settings          Run 02 validation/shared or compatible campaign settings.
%   target            Target struct with body_name and vinf_earth_rth_km_s.
%   target_frame      eci or rth.
%   theta_sun0_value  Initial Sun phase [rad].
%
% OUTPUT:
%   params            Struct for RPO2DS_transfer; altitude is in km, time caps
%                      in days, lunar velocity tolerances in km/s, and initial
%                      geometry time in normalized TU. See the solver header
%                      for the corresponding field meanings.

if isfield(settings, 'shared')
    shared = settings.shared;
else
    shared = struct('sun_angular_rate_rad_tu', -9.25195985e-1);
end
if ~isfield(settings, 'time_variable_mode')
    settings.time_variable_mode = 'propagation_times';
end
if ~isfield(settings, 'minimum_earth_altitude_km')
    settings.minimum_earth_altitude_km = settings.initial_earth_altitude_km;
end
if ~isfield(settings, 'node_count')
    settings.node_count = 80;
end
if ~isfield(settings, 'node_count_mode')
    settings.node_count_mode = 'adaptive_plus';
end
params = struct( ...
    'n_nodes', settings.node_count, ...
    'node_count_mode', settings.node_count_mode, ...
    'nodes_per_day', settings.nodes_per_day, ...
    'n_nodes_min', 2, ...
    'n_nodes_max', 200, ...
    'adaptive_plus_divisions', 10, ...
    'adaptive_plus_upstream_nodes', 4, ...
    'hStart', settings.minimum_earth_altitude_km, ...
    'N', settings.earth_perigee_samples, ...
    'nMoonOrbitSamples', settings.moon_samples, ...
    'feasibleLimit', local_match_tolerance(settings, target), ...
    'maxTOF', local_max_tof(settings), ...
    'maxTransferTOF', settings.maximum_transfer_time_days, ...
    'time_mode', 'max_time', ...
    'time_variable_mode', settings.time_variable_mode, ...
    'geometry_mode', 'free_geometry', ...
    'initial_geometry_time', 0, ...
    'phase_mode', 'no_phase', ...
    'phase_value', 0, ...
    'operational_mode', 'standard', ...
    'initial_epoch_time', 0, ...
    'initial_rpo_phase', 0, ...
    'final_epoch_time', [], ...
    'operational_seed_pool_size', local_seed_pool(settings), ...
    'target_frame', target_frame, ...
    'vinf_target_rth_km_s', target.vinf_earth_rth_km_s(:), ...
    'theta_sun0_mode', 'specified', ...
    'theta_sun0_value', theta_sun0_value, ...
    'theta_sun0_seed', theta_sun0_value, ...
    'ws_sun_em_nd', shared.sun_angular_rate_rad_tu, ...
    'rth_seed_target_iterations', 2, ...
    'rth_seed_nominal_lambert_tof_days', 8, ...
    'rth_seed_max_lambert_tof_days', settings.maximum_transfer_time_days, ...
    'rth_seed_epoch_nodes', settings.moon_samples, ...
    'dense_nodes_multiplier', 0.15);
end

function tolerance = local_match_tolerance(settings, target)
%LOCAL_MATCH_TOLERANCE Read the shared or target-specific lunar match tolerance [km/s].

if isfield(settings, 'rpo_moon_match_tolerance_km_s')
    tolerance = settings.rpo_moon_match_tolerance_km_s;
else
    field_name = ['rpo_moon_match_tolerance_' lower(char(target.body_name)) '_km_s'];
    if isfield(settings, field_name)
        tolerance = settings.(field_name);
    else
        tolerance = 0.01;
    end
end
end

function value = local_max_tof(settings)
%LOCAL_MAX_TOF Prefer the total-time cap over the transfer-only cap [days].

if isfield(settings, 'maximum_total_time_days')
    value = settings.maximum_total_time_days;
else
    value = settings.maximum_transfer_time_days;
end
end

function value = local_seed_pool(settings)
%LOCAL_SEED_POOL Use the configured operational seed-pool size, defaulting to one.

if isfield(settings, 'operational_seed_pool_size')
    value = settings.operational_seed_pool_size;
else
    value = 1;
end
end
