function numbers = figure_numbers(output_directory)
%FIGURE_NUMBERS Fixed scientific ordering, shared by all figure exporters.
%
% PROTOTYPE:
%   numbers = rpo.figure_numbers(output_directory)
%
% DESCRIPTION:
%   Select the complete figure order from the final study directory name.
%   The map includes all figures, so independently run sections retain their
%   assigned numbers. An unregistered study folder raises an error.
%
% INPUT:
%   output_directory  Path ending in one of the 01_reference_rpo through
%                       06_comet_case_study study folder names.
%
% OUTPUT:
%   numbers           containers.Map from figure base names to integer numbers.

% Keep the full order here so section-only exports cannot renumber figures.
[~, study] = fileparts(output_directory);
switch study
    case '01_reference_rpo'
        names = ["a1_family_samples", "reference_rpo_family", ...
            "a1_planar_stability", "a1_spatial_stability", "rpo_poincare_section", ...
            "rpo_vertical_perturbation_magnitudes", "rpo_vertical_trajectory", ...
            "rpo_vertical_phase_response"];
    case '02_rpo_to_deep_space'
        names = ["rpo_moon_encounter_map", "earth_departure_construction", ...
            "venus_mars_target_transfers", "escape_direction_altitude_comparison", ...
            "venus_patched_initial_guess", "venus_multiple_shooting_nodes", ...
            "venus_optimized_rotating", "venus_optimized_inertial", ...
            "mars_patched_initial_guess", "mars_multiple_shooting_nodes", ...
            "mars_optimized_rotating", "mars_optimized_inertial", ...
            "flexibility_delta_v_before_tuning", "flexibility_delta_v_after_tuning", ...
            "flexibility_time_of_flight_after_tuning", ...
            "escape_reachability_curve", "escape_velocity_cloud"];
    case '03_earth_to_rpo'
        names = ["TOFvsC3_1000_highlights", "TOFvsC3_10000", ...
            "Sample_solution_1", "Sample_solution_2", "initial_guess_full", ...
            "initial_guess_zoom", "initial_guess_full_nodes", ...
            "initial_guess_zoom_nodes", "initial_guess_zoomzoom_nodes", ...
            "vleo_rpo_optimized_rot", "vleo_rpo_optimized_rot_leo_closeup", ...
            "vleo_rpo_optimized_rot_rpo_closeup", "vleo_rpo_optimized_inertial", ...
            "vleo_rpo_optimized_inertial_leo_closeup", ...
            "vleo_rpo_optimized_inertial_rpo_closeup", "leo_rpo_altitude_sweep_stacked_dv"];
    case '04_sel2_to_rpo'
        names = ["sel2_reference_halo", "sel2_unstable_direction_projections", ...
            "sel2_rpo_database_proxy_pareto", "sel2_rpo_initial_guess", ...
            "sel2_rpo_multiple_shooting_nodes", "sel2_rpo_optimized_sun_earth", ...
            "sel2_rpo_optimized_earth_moon", "sel2_rpo_continuation_delta_v", ...
            "sel2_rpo_continuation_times"];
    case '05_stationkeeping'
        names = "stationkeeping_cost_cdf";
    case '06_comet_case_study'
        names = ["warning_law_generation", "l1_l2_full_tof_accessibility", ...
            "l1_l2_limited_time_accessibility", "l1_full_tof_accessibility", ...
            "l1_limited_time_accessibility", "l2_full_tof_accessibility", ...
            "l2_limited_time_accessibility", "earth_full_tof_accessibility", ...
            "earth_limited_time_accessibility", "rpo_first_direction_calibration", ...
            "rpo_rth_polar_boundary", "monte_carlo_l1_l2", "monte_carlo_mixed"];
    otherwise
        error('rpo:FigureOrder', 'Define the figure order for output folder %s.', study);
end
numbers = containers.Map(cellstr(names), num2cell(1:numel(names)));
end
